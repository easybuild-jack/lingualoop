import { API_URL, ANON_KEY, PSQL, resetDatabase, storage, check, summary } from './env'
import { execSync } from 'node:child_process'

function sql(query: string): string {
  return execSync(`${PSQL} -Atc ${JSON.stringify(query)}`).toString().trim()
}

async function main() {
  resetDatabase()
  const config = await import('../../src/core/cloud/config')
  const account = await import('../../src/core/cloud/account')
  const { localRepositories, getRepositories } = await import('../../src/db/repository')
  const dbIndex = await import('../../src/db/index')
  const { DEFAULT_SAMPLE_CUSTOM_BOOK } = await import('../../src/resources/books')
  const { createScopedProgressStorage } = await import('../../src/core/cloud/scopedStorage')
  const sync = await import('../../src/core/cloud/manualSync')

  console.log('# pure local mode')
  check('no config -> local repositories', getRepositories().mode === 'local')
  await dbIndex.recordWordAttempt('w_local', 'cet4', false, 'dictation')
  await dbIndex.markUnitWordCompleted({ bookId: 'cet4', unitId: 'cet4_semantic_1', mode: 'learn', wordId: 'w_local', wordIndex: 0, unitWordIds: ['w_local', 'w2'] })
  await dbIndex.toggleStarWord('w_star', 'cet4')
  check('local record written to IndexedDB', (await localRepositories.wordRecords.get('w_local'))?.isError === true)
  check('local unit progress written', (await localRepositories.unitProgress.get('cet4_semantic_1', 'learn'))?.completedWordIds.length === 1)
  check('local starred ids', JSON.stringify(await dbIndex.getStarredWordIds()) === '["w_star"]')
  const custom = await dbIndex.getCustomBooks()
  check('local getCustomBooks seeds sample book', custom[0]?.id === DEFAULT_SAMPLE_CUSTOM_BOOK.id)
  const personalLocal = await dbIndex.saveCustomVocabularyBook('local book', '', [{ id: 'w_l', name: 'l', syllables: ['l'], posList: [] }])
  check('local saved book has no accountId', personalLocal.accountId === undefined)
  check('local AI fill written into the local custom book', (await dbIndex.applyAiFillToCustomBook(personalLocal.id, 'w_l', { phoneticUs: '/l/' })) && (await localRepositories.books.get(personalLocal.id))?.words[0].phoneticUs === '/l/')
  check('AI fill never touches official books', !(await dbIndex.applyAiFillToCustomBook('cet4', 'w_l', { phoneticUs: '/x/' })))
  await localRepositories.books.put({ ...(await localRepositories.books.get(personalLocal.id))!, words: personalLocal.words })
  const scoped = createScopedProgressStorage(['currentBookId'])
  scoped.setItem('ws', JSON.stringify({ state: { currentBookId: 'local-book', theme: 'dark' }, version: 1 }))
  check('local mode persist writes base key unchanged', JSON.parse(storage.getItem('ws')!).state.currentBookId === 'local-book')
  storage.setItem('lingualoop-workspace-storage', JSON.stringify({
    state: { currentBookId: 'cet4', currentUnitIndex: 4, bookModeProgress: { cet4: { learn: 4, dictation: 2, phonetic: 0 } }, loopCounts: { learn: 1, dictation: 3, phonetic: 1 }, learnedRootIds: ['r1'] },
    version: 0,
  }))

  console.log('# cloud: scoped persist storage')
  config.saveCloudConfig(API_URL, ANON_KEY)
  check('config -> cloud repositories', getRepositories().mode === 'cloud')
  check('cloud mode not signed in: progress not read', scoped.getItem('ws') === JSON.stringify({ state: { theme: 'dark' }, version: 1 }), scoped.getItem('ws'))
  const carol = await account.registerAccount('carol', 'secret1')
  scoped.getItem('ws') // 登录后整页重载：按新账号重新水合
  scoped.setItem('ws', JSON.stringify({ state: { currentBookId: 'carol-book', theme: 'light' }, version: 1 }))
  check('cloud write keeps local progress in base key', JSON.parse(storage.getItem('ws')!).state.currentBookId === 'local-book')
  check('cloud write stores settings in base key', JSON.parse(storage.getItem('ws')!).state.theme === 'light')
  check('cloud mode stores no progress locally', storage.keys().every((key) => !key.includes('::cloud::')), storage.keys())
  check('cloud read still returns no progress', !('currentBookId' in JSON.parse(scoped.getItem('ws') as string).state))

  console.log('# manual sync: content (同步资料)')
  const w = (id: string, mean: string) => ({ id, name: id, syllables: [id], posList: [{ pos: 'n.' as const, means: [mean] }] })
  const TS = 'lingualoop-translate-storage'
  const RS = 'lingualoop_reading_articles_v1'
  const sentence = (id: string, en: string) => ({ id, sentenceEn: en, sentenceZh: en })
  storage.setItem(TS, JSON.stringify({ state: { books: [{ id: 'custom_tb_1', name: 'tb', category: 'custom', isCustom: true, totalSentences: 1, sentences: [sentence('s1', 'one')], createdAt: 1, updatedAt: 1 }], completedSentenceIds: { s1: true, s2: true } }, version: 0 }))
  storage.setItem(RS, JSON.stringify([{ id: 'art_1', title: 'A', paragraphs: [{ en: 'x', zh: 'y' }], isCustom: true, createdAt: 1 }]))
  const c1 = await sync.syncLocalContentToCloud('personal')
  check('new custom books added (sample + local book)', c1.books.added === 2 && c1.books.skipped === 0, c1)
  check('new translate book and article added', c1.translateBooks.added === 1 && c1.articles.added === 1, c1)
  check('added content uses the chosen ownership', sql(`select count(*) from vocab_books where account_id='${carol.accountId}'`) === '2' && sql(`select account_id from translate_books where id='custom_tb_1'`) === carol.accountId)
  const c2 = await sync.syncLocalContentToCloud('personal')
  check('repeat content sync changes nothing', c2.books.added + c2.books.updated + c2.translateBooks.updated + c2.articles.updated === 0, c2)
  check('nothing-to-do message', sync.formatContentSyncResult(c2).includes('没有需要同步'), sync.formatContentSyncResult(c2))
  sql(`update vocab_books set words = words || '[{"id":"db_only","name":"db","syllables":["db"],"posList":[]}]'::jsonb where id='${personalLocal.id}'`)
  await localRepositories.books.put({ ...personalLocal, words: [w('w_l', 'changed'), w('w_new', 'new')], totalWords: 2 })
  const c3 = await sync.syncLocalContentToCloud('personal')
  check('existing book: words updated and appended', c3.books.updated === 1 && c3.words.updated === 1 && c3.words.added === 1, c3)
  check('words only in the database are kept', sql(`select string_agg(e->>'id', ',' order by ord) from vocab_books, jsonb_array_elements(words) with ordinality as t(e, ord) where id='${personalLocal.id}'`) === 'w_l,db_only,w_new')
  const zed = await account.registerAccount('zed', 'secret1')
  sql(`insert into vocab_books(id, account_id, name, category, is_custom, unit_size, words) values ('book_custom_zed', '${zed.accountId}', 'zed', 'custom', true, 20, '[]'::jsonb)`)
  sql(`insert into vocab_books(id, account_id, name, category, is_custom, unit_size, words) values ('book_custom_shared_x', null, 'sx', 'custom', true, 20, '[]'::jsonb)`)
  config.saveCloudSession({ accountId: carol.accountId, username: 'carol', displayName: null })
  await localRepositories.books.put({ ...personalLocal, id: 'book_custom_zed', name: 'mine?', words: [w('z1', 'z')] })
  await localRepositories.books.put({ ...personalLocal, id: 'book_custom_shared_x', name: 'sx', words: [w('x1', 'x')] })
  storage.setItem(TS, JSON.stringify({ state: { books: [{ id: 'custom_tb_1', name: 'tb', category: 'custom', isCustom: true, totalSentences: 2, sentences: [sentence('s1', 'one!'), sentence('s9', 'nine')], createdAt: 1, updatedAt: 1 }], completedSentenceIds: { s1: true, s2: true } }, version: 0 }))
  const c4 = await sync.syncLocalContentToCloud('personal')
  check("other account's personal book skipped and counted", c4.books.skipped === 1 && sql("select jsonb_array_length(words) from vocab_books where id='book_custom_zed'") === '0', c4)
  check('existing shared book is updated even with 个人 chosen, stays shared', sql("select jsonb_array_length(words)||':'||coalesce(account_id::text,'null') from vocab_books where id='book_custom_shared_x'") === '1:null')
  check('translate sentences merged by id', c4.sentences.updated === 1 && c4.sentences.added === 1 && sql("select jsonb_array_length(sentences) from translate_books where id='custom_tb_1'") === '2', c4)
  check('skip message mentions content not owned', sync.formatContentSyncResult(c4).includes('不属于你的内容'), sync.formatContentSyncResult(c4))
  await localRepositories.books.delete('book_custom_zed')
  await localRepositories.books.delete('book_custom_shared_x')
  sql("delete from vocab_books where id in ('book_custom_zed', 'book_custom_shared_x')")

  console.log('# manual sync: progress (同步进度)')
  const p1 = await sync.syncLocalProgressToCloud()
  check('word records added', p1.wordRecords.added === 2, p1)
  check('official unit progress added', p1.unitProgress.added === 1 && sql(`select count(*) from unit_progress where account_id='${carol.accountId}' and book_kind='official'`) === '1', p1)
  check('only non-zero book positions added', p1.bookProgress.added === 2 && sql('select count(*) from book_progress where unit_index = 0') === '0', p1)
  check('app_state created from local', p1.appState.added === 1, p1)
  check('translate completed ids added', p1.translateCompleted.added === 2, p1)
  const remote = await getRepositories().appState.get()
  check('synced app_state position', remote?.currentBookId === 'cet4' && remote.currentUnitIndex === 4 && remote.bookModeProgress.cet4?.learn === 4, remote)
  const p2 = await sync.syncLocalProgressToCloud()
  check('repeat progress sync changes nothing', sync.formatProgressSyncResult(p2).includes('没有改动'), sync.formatProgressSyncResult(p2))

  const wordRow = (id: string) => sql(`select total_practice_count||':'||is_error||':'||is_starred from word_records where account_id='${carol.accountId}' and word_id='${id}'`)
  sql(`update word_records set total_practice_count = 10, is_error = false, consecutive_correct_count = 3, last_practiced_at = ${Date.now() + 60_000} where account_id='${carol.accountId}' and word_id='w_local'`)
  const localStar = (await localRepositories.wordRecords.get('w_star'))!
  await localRepositories.wordRecords.put({ ...localStar, isError: true, totalPracticeCount: 3, lastPracticedAt: Date.now() + 120_000 })
  sql(`update book_progress set unit_index = 7, updated_at = ${Date.now()} where account_id='${carol.accountId}' and book_id='cet4' and mode='learn'`)
  storage.setItem('lingualoop-workspace-storage', JSON.stringify({
    state: { currentBookId: 'cet6', currentUnitIndex: 1, bookModeProgress: { cet4: { learn: 4, dictation: 5, phonetic: 0 } }, loopCounts: { learn: 1, dictation: 3, phonetic: 1 }, learnedRootIds: ['r1', 'r2'] },
    version: 0,
  }))
  const localUnit = (await localRepositories.unitProgress.get('cet4_semantic_1', 'learn'))!
  await localRepositories.unitProgress.put({ ...localUnit, completedWordIds: ['w2'], currentWordIndex: 1 })
  const p3 = await sync.syncLocalProgressToCloud()
  check('error mark added back regardless of time, count not lowered', wordRow('w_local') === '10:true:false', wordRow('w_local'))
  check('re-added error word takes the streak of the error side', sql(`select consecutive_correct_count from word_records where account_id='${carol.accountId}' and word_id='w_local'`) === '0')
  check('error mark from local added, counts take the larger value', wordRow('w_star') === '3:true:true' && p3.wordRecords.updated === 2, [wordRow('w_star'), p3.wordRecords])
  sql(`update word_records set is_error = true, consecutive_correct_count = 1 where account_id='${carol.accountId}' and word_id='w_star'`)
  await localRepositories.wordRecords.put({ ...(await localRepositories.wordRecords.get('w_star'))!, isError: false, consecutiveCorrectCount: 3 })
  const p4 = await sync.syncLocalProgressToCloud()
  check('local without the error mark never removes it from the database', sql(`select is_error||':'||consecutive_correct_count from word_records where account_id='${carol.accountId}' and word_id='w_star'`) === 'true:1' && p4.wordRecords.updated === 0, p4.wordRecords)
  check('unit progress completed ids merged as union', sql(`select completed_word_ids::text from unit_progress where account_id='${carol.accountId}' and unit_id='cet4_semantic_1'`) === '["w_local", "w2"]' && p3.unitProgress.updated === 1, p3.unitProgress)
  check('book position only raised, never lowered', sql(`select string_agg(mode||'='||unit_index, ',' order by mode) from book_progress where account_id='${carol.accountId}' and book_id='cet4'`) === 'dictation=5,learn=7', p3.bookProgress)
  const remote2 = await getRepositories().appState.get()
  check('existing position kept, learned roots merged', remote2?.currentBookId === 'cet4' && JSON.stringify(remote2.learnedRootIds) === '["r1","r2"]' && p3.appState.updated === 1, remote2)

  console.log('# sample book with fixed id (suspected issue)')
  sql(`update vocab_books set words = '[{"id":"carol_w","name":"carol","syllables":["carol"],"posList":[]}]'::jsonb where id='${DEFAULT_SAMPLE_CUSTOM_BOOK.id}'`)
  const dave = await account.registerAccount('dave', 'secret1')
  const daveBooks = await dbIndex.getCustomBooks()
  check('dave is not shown an unwritable sample book', daveBooks.length === 0, daveBooks.map((b) => b.id))
  const sampleWords = sql(`select words::text from vocab_books where id='${DEFAULT_SAMPLE_CUSTOM_BOOK.id}'`)
  check('carol personal sample book NOT overwritten by dave', sampleWords.includes('carol_w'), sampleWords.slice(0, 120))
  check('sample book still owned by carol', sql(`select account_id from vocab_books where id='${DEFAULT_SAMPLE_CUSTOM_BOOK.id}'`) === carol.accountId)
  sql(`delete from vocab_books where id='${DEFAULT_SAMPLE_CUSTOM_BOOK.id}'`)
  const daveBooks2 = await dbIndex.getCustomBooks()
  check('when the sample id is free it is inserted as shared and returned', daveBooks2[0]?.id === DEFAULT_SAMPLE_CUSTOM_BOOK.id && daveBooks2[0]?.accountId === null, daveBooks2.map((b) => [b.id, b.accountId]))
  const daveMerge = await dbIndex.mergeWordsIntoBook(DEFAULT_SAMPLE_CUSTOM_BOOK.id, [{ id: 'd1', name: 'd', syllables: [], posList: [] }])
  check('dave can import into the shared sample book', daveMerge !== null)

  console.log('# import into an existing book follows ownership')
  const word = (id: string, mean: string) => ({ id, name: id, syllables: [id], posList: [{ pos: 'n.' as const, means: [mean] }] })
  const asCarol = () => config.saveCloudSession({ accountId: carol.accountId, username: 'carol', displayName: null })
  const asDave = () => config.saveCloudSession({ accountId: dave.accountId, username: 'dave', displayName: null })
  asCarol()
  const carolBook = await dbIndex.saveCustomVocabularyBook('carol p', '', [word('a', 'old'), word('b', 'keep')], carol.accountId)
  const sharedBook = await dbIndex.saveCustomVocabularyBook('shared s', '', [word('s1', 'old')], null)
  const partial = await dbIndex.importWordsIntoBook(carolBook.id, [word('a', 'new'), word('c', 'added')], 'personal')
  const partialWords = partial.book?.words ?? []
  check('own personal book: existing updated, new added, nothing skipped', partial.updated === 1 && partial.added === 1 && partial.skipped === 0, partial)
  check('words missing from the import are kept', partialWords.map((w) => w.id).join() === 'a,b,c' && partialWords[0].posList[0].means[0] === 'new', partialWords.map((w) => [w.id, w.posList[0]?.means[0]]))
  const wrongChoice = await dbIndex.importWordsIntoBook(carolBook.id, [word('a', 'x')], 'shared')
  check('personal book with 共享 chosen is skipped (not-shared)', wrongChoice.skipped === 1 && wrongChoice.skipReason === 'not-shared', wrongChoice)
  asDave()
  const sharedUpdate = await dbIndex.importWordsIntoBook(sharedBook.id, [word('s1', 'new'), word('s2', 'added')], 'shared')
  check('anyone can update/add in a shared book', sharedUpdate.updated === 1 && sharedUpdate.added === 1, sharedUpdate)
  const notOwned = await dbIndex.importWordsIntoBook(sharedBook.id, [word('s1', 'x'), word('s3', 'y')], 'personal')
  check('shared book with 个人 chosen: all skipped and counted (not-owned)', notOwned.skipped === 2 && notOwned.skipReason === 'not-owned', notOwned)
  check('skipped import changed nothing', sql(`select jsonb_array_length(words) from vocab_books where id='${sharedBook.id}'`) === '2')
  const invisible = await dbIndex.importWordsIntoBook(carolBook.id, [word('a', 'hack')], 'personal')
  check("other account's personal book is skipped (missing)", invisible.skipped === 1 && invisible.skipReason === 'missing', invisible)
  check("carol's book untouched by dave", sql(`select words->0->'posList'->0->'means'->>0 from vocab_books where id='${carolBook.id}'`) === 'new')

  console.log('# AI fill written back to database books by ownership')
  asDave()
  check('shared book: AI fill written', await dbIndex.applyAiFillToCustomBook(sharedBook.id, 's1', { phrases: [{ en: 'p', cn: 'q' }] }))
  check('shared book word has the phrase, other fields kept', sql(`select (e->'phrases'->0->>'en')||':'||(e->'posList'->0->'means'->>0) from vocab_books, jsonb_array_elements(words) e where id='${sharedBook.id}' and e->>'id'='s1'`) === 'p:new')
  check("other account's personal book: not written", !(await dbIndex.applyAiFillToCustomBook(carolBook.id, 'a', { phoneticUs: '/hack/' })))
  asCarol()
  check('own personal book: AI fill written', await dbIndex.applyAiFillToCustomBook(carolBook.id, 'a', { phoneticUs: '/a/' }))
  check("own book word updated in the database", sql(`select e->>'phoneticUs' from vocab_books, jsonb_array_elements(words) e where id='${carolBook.id}' and e->>'id'='a'`) === '/a/')

  console.log('# inbox (H6)')
  config.saveCloudSession({ accountId: carol.accountId, username: 'carol', displayName: null })
  sql(`insert into collected_words(word, word_item, source) values ('apple', '{"name":"apple","syllables":["ap","ple"],"posList":[{"pos":"n.","means":["苹果"]}]}', 'tool')`)
  sql(`insert into collected_words(word) values ('hello world!!')`)
  sql(`insert into collected_words(word) values ('zzqxv')`)
  const { pullCollectedWords, collectedBookId } = await import('../../src/core/cloud/collector')
  const pulled = await pullCollectedWords()
  check('apple collected', pulled?.added.map((w) => w.name).join() === 'apple', pulled)
  check('apple starred for carol', sql(`select is_starred from word_records where account_id='${carol.accountId}' and word_id='${(await import('../../src/lib/wordId')).buildWordId('apple')}'`) === 't')
  check('collected book is carol personal', sql(`select account_id from vocab_books where id='${collectedBookId(carol.accountId)}'`) === carol.accountId)
  check('non-word marked failed (terminal)', sql(`select status from collected_words where word='hello world!!'`) === 'failed')
  check('lookup failure is retryable (pending)', sql(`select status||':'||attempts from collected_words where word='zzqxv'`) === 'pending:1', sql(`select status||':'||attempts||':'||coalesce(last_error,'') from collected_words where word='zzqxv'`))
  for (let i = 0; i < 5; i += 1) await pullCollectedWords()
  check('retryable failure becomes terminal after max attempts', sql(`select status from collected_words where word='zzqxv'`) === 'failed', sql(`select status||':'||attempts from collected_words where word='zzqxv'`))
  check('nothing stuck in processing', sql(`select count(*) from collected_words where status='processing'`) === '0')

  summary()
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
